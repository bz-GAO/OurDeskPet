import {build} from 'esbuild';
import {mkdtemp, rm} from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
const temp = await mkdtemp(path.resolve('node_modules/.tomo-state-test-'));
try {
  const file = path.join(temp, 'state.mjs');
  await build({entryPoints: ['src/extensions/rinatomo/tomoState.ts'], outfile: file, bundle: true, platform: 'node', format: 'esm'});
  const {preview, fromSnapshot, mergeDraft, parseIds, parseNightTime, parseNonNegativeNumber, parsePositiveInteger, serviceControls} = await import(pathToFileURL(file));
  assert.equal(preview.owner, null, 'offline snapshot has no lifecycle owner');
  const running = {...preview, available: true, running: true};
  assert.equal(serviceControls(running).canStart, true, 'old controllers remain compatible');
  const closing = serviceControls({...running, shuttingDown: true});
  assert.equal(closing.canStart, false);
  assert.equal(closing.canShutdown, false);
  const failed = serviceControls({...running, running: false, shutdownError: '关闭失败'});
  assert.equal(failed.canStart, false, 'failed cleanup must not create a second pipeline');
  assert.equal(failed.showShutdown, true, 'failed cleanup retains the retry action');
  assert.equal(failed.canShutdown, true);
  const draft = fromSnapshot(preview);
  draft.permissions.adminUsers = '10001';
  draft.llm.minReplyInterval = '2.5';
  draft.notifications.nightStart = '23:30';
  const incoming = {...preview, available: true, autoStart: true, features: {...preview.features, ping: false}, llm: {...preview.llm, enabled: true, minReplyInterval: 5}};
  const result = mergeDraft(draft, incoming, {features: false, llm: true, permissions: true, autoStart: false, notifications: true});
  assert.equal(result.permissions.adminUsers, '10001', 'applying features preserves unsaved permissions');
  assert.equal(result.llm.minReplyInterval, '2.5', 'polling preserves unsaved LLM settings');
  assert.equal(result.notifications.nightStart, '23:30', 'polling preserves unsaved notification settings');
  assert.equal(result.features.ping, false);
  assert.equal(result.autoStart, true, 'clean groups receive remote changes');
  assert.equal(mergeDraft(result, preview, {features: false, llm: true, permissions: true, autoStart: false, notifications: true}).autoStart, true);
  assert.deepEqual(parseIds('10001，10002 10001', 'QQ'), [10001, 10002]);
  for (const value of ['1e5', '0x12', '0', '-1', '9007199254740992']) assert.throws(() => parseIds(value, 'QQ'));
  assert.equal(parseNonNegativeNumber('0', '间隔'), 0);
  assert.equal(parseNonNegativeNumber('2.5', '间隔'), 2.5);
  for (const value of ['', '-1', 'NaN']) assert.throws(() => parseNonNegativeNumber(value, '间隔'));
  assert.equal(parsePositiveInteger('300', 'token'), 300);
  for (const value of ['0', '1.5', 'abc']) assert.throws(() => parsePositiveInteger(value, 'token'));
  assert.equal(parseNightTime(' 07:05 ', '时间'), '07:05');
  for (const value of ['7:05', '24:00', '12:60', '']) assert.throws(() => parseNightTime(value, '时间'));
  console.log('PASS Tomo cross-group drafts, remote sync, offline recovery and ID validation');
} finally {await rm(temp, {recursive: true, force: true});}
